export function helpWords(lang) {
  const base = String(lang || 'en').toLowerCase().split(/[-_]/)[0]
  return Object.assign({}, T.en, T[base] || {})
}

export function fill(s, vars) {
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? vars[k] : m))
}

